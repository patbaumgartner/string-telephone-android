#!/usr/bin/env bash
#
# Asterisk entrypoint wrapper.
#
# Generates the PJSIP TLS transport section from mounted certificate files and
# then delegates to the image's own entrypoint (which adapts the asterisk user
# and finally execs the CMD). SIP over UDP on 5060 is always available; TLS on
# 5061 is additive and only configured when certificates are present, so the
# prototype stack keeps working unsecured when no certs are mounted.
#
# Environment:
#   PJSIP_TLS_ENABLE      auto | true | false  (default auto)
#                         auto  -> enable when both cert and key are readable
#                         true  -> require cert and key, fail otherwise
#                         false -> never configure TLS
#   PJSIP_TLS_CERTS_DIR   directory holding the certs (default /certs)
#   PJSIP_TLS_CERT_FILE   certificate chain (default <dir>/fullchain.pem)
#   PJSIP_TLS_KEY_FILE    private key       (default <dir>/privkey.pem)
#   PJSIP_TLS_PORT        listen port       (default 5061)
#   PJSIP_TLS_METHOD      TLS method list   (default tlsv1_2)
#   PJSIP_TLS_CONF        generated include (default /etc/asterisk/pjsip-tls.conf)
set -euo pipefail

CERTS_DIR="${PJSIP_TLS_CERTS_DIR:-/certs}"
CERT_FILE="${PJSIP_TLS_CERT_FILE:-${CERTS_DIR}/fullchain.pem}"
KEY_FILE="${PJSIP_TLS_KEY_FILE:-${CERTS_DIR}/privkey.pem}"
TLS_PORT="${PJSIP_TLS_PORT:-5061}"
TLS_METHOD="${PJSIP_TLS_METHOD:-tlsv1_2}"
TLS_CONF="${PJSIP_TLS_CONF:-/etc/asterisk/pjsip-tls.conf}"
TLS_ENABLE="${PJSIP_TLS_ENABLE:-auto}"

write_tls_transport() {
    cat >"${TLS_CONF}" <<EOF
; Generated by docker-entrypoint.sh at container start; overwritten on every
; boot. The unsecured [transport-udp] lives in pjsip.conf and is unaffected.
[transport-tls]
type=transport
protocol=tls
bind=0.0.0.0:${TLS_PORT}
cert_file=${CERT_FILE}
priv_key_file=${KEY_FILE}
method=${TLS_METHOD}
EOF
}

write_disabled() {
    # Keep the #include target present so Asterisk logs no missing-file warning.
    printf '; SIP over TLS is disabled (no certificates mounted).\n' >"${TLS_CONF}"
}

have_certs() {
    [[ -r "${CERT_FILE}" && -r "${KEY_FILE}" ]]
}

case "${TLS_ENABLE}" in
    true)
        if ! have_certs; then
            echo "PJSIP_TLS_ENABLE=true but certificates are missing:" \
                 "${CERT_FILE} / ${KEY_FILE}" >&2
            exit 1
        fi
        write_tls_transport
        echo "SIP/TLS enabled on 0.0.0.0:${TLS_PORT} (cert ${CERT_FILE})"
        ;;
    false)
        write_disabled
        echo "SIP/TLS disabled by PJSIP_TLS_ENABLE=false"
        ;;
    auto)
        if have_certs; then
            write_tls_transport
            echo "SIP/TLS enabled on 0.0.0.0:${TLS_PORT} (cert ${CERT_FILE})"
        else
            write_disabled
            echo "SIP/TLS disabled: no certificates under ${CERTS_DIR}"
        fi
        ;;
    *)
        echo "Invalid PJSIP_TLS_ENABLE='${TLS_ENABLE}' (expected auto, true, or false)" >&2
        exit 1
        ;;
esac

exec /usr/local/bin/entrypoint.sh "$@"
